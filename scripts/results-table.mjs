#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const dir = process.argv[2] ?? "results";
const load = (name) => {
  const file = `${dir}/${name}.json`;
  return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : null;
};
const fmt = (v, unit = "") => (v === undefined || v === null || Number.isNaN(v) ? "—" : `${typeof v === "number" ? v.toLocaleString("en-US") : v}${unit}`);

const rows = [];
const idle = load("idle");
if (idle !== null) {
  const r = idle.result;
  rows.push(["idle", fmt(r.connections), "—", "—", "—", fmt(r.server.eventLoopP99MsMax, " ms"), `${fmt(r.heapPerConnSlopeKb ?? r.heapPerConnKb, " KB")} heap, ${fmt(r.rssPerConnKb, " KB")} RSS`, "—"]);
}
for (const [name, group] of [
  ["fanout-big-room", "big-room"],
  ["many-rooms", "normal"],
  ["many-rooms-3000-overload", "normal"],
  ["many-rooms-6000-overload", "normal"],
  ["many-rooms-scaled-watermarks", "normal"],
  ["slow-consumers", "normal"],
  ["resume", "chaos"],
]) {
  const run = load(name);
  if (run === null) continue;
  const r = run.result;
  const lat = r.latencyMs[group] ?? {};
  rows.push([name, fmt(r.connections), fmt(r.server.msgsOutPerSec), fmt(lat.p50, " ms"), fmt(lat.p99, " ms"), fmt(r.server.eventLoopP99MsMax, " ms"), "—", `${r.gaps} gaps / ${r.duplicates} dups`]);
}
for (const name of ["reconnect-storm-no-jitter", "reconnect-storm-jitter"]) {
  const run = load(name);
  if (run === null) continue;
  const r = run.result;
  rows.push([name, fmt(r.connections), "—", "—", `ticket p99 ${fmt(r.ticketLatencyMs.p99, " ms")}`, fmt(r.server.eventLoopP99MsMax, " ms"), "—", `${r.gaps} gaps / ${r.duplicates} dups`]);
}

const header = ["Scenario", "Connections", "Msgs out/s", "p50", "p99", "Event loop p99", "Memory / conn", "Correctness"];
const lines = [`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)];
const out = lines.join("\n") + "\n";
writeFileSync(`${dir}/RESULTS.md`, `# Load test summary\n\nGenerated by scripts/results-table.mjs from the JSON files in this directory.\n\n${out}`);
console.log(out);
